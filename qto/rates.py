"""Rate library: import, export and apply unit rates to BOQ lines."""

from __future__ import annotations

import io
import re
from difflib import SequenceMatcher

import pandas as pd

from . import boq
from .schedules import TEMPLATES, normalise_unit, to_number

COLUMNS = ["Code", "Description", "Unit", "Rate", "Discipline", "Work Section"]
AUTO_REF = re.compile(r"^[A-Z]\.\d{2}\.\d{3}$")  # refs generated by boq.finalise, not real item codes
CANDIDATES = 25  # best token-overlap candidates scored in detail per BOQ line


def empty() -> pd.DataFrame:
    # Built through tidy() so dtypes match what the library editor produces.
    return tidy(pd.DataFrame(columns=COLUMNS), drop_blank=False)


def tidy(library: pd.DataFrame, drop_blank: bool = True) -> pd.DataFrame:
    """Standard columns and types; rows without a description are dropped unless drop_blank is False."""
    out = library.copy()
    for column in COLUMNS:
        if column not in out:
            out[column] = "" if column != "Rate" else 0.0
    out = out[COLUMNS]
    for column in COLUMNS:
        if column != "Rate":
            out[column] = out[column].fillna("").astype(str).str.strip().replace("nan", "")
    out["Unit"] = out["Unit"].map(normalise_unit)
    out["Rate"] = pd.to_numeric(out["Rate"], errors="coerce").fillna(0.0).astype(float)
    if drop_blank:
        out = out[out["Description"] != ""]
    return out.reset_index(drop=True)


def template() -> pd.DataFrame:
    """Blank library layout with example descriptions; the user fills in the rates."""
    rows = [
        {"Code": code, "Description": desc, "Unit": unit, "Rate": None, "Discipline": discipline, "Work Section": section}
        for discipline, items in TEMPLATES.items()
        for code, desc, unit, _qty, section in items
    ]
    return pd.DataFrame(rows, columns=COLUMNS)


def from_table(table: pd.DataFrame, mapping: dict[str, str | None], discipline: str | None = None) -> pd.DataFrame:
    """Convert an uploaded sheet into library rows using a column mapping."""
    def col(field):
        name = mapping.get(field)
        return table[name] if name in table else pd.Series([None] * len(table), index=table.index)

    out = pd.DataFrame({
        "Code": col("Code"),
        "Description": col("Description"),
        "Unit": col("Unit"),
        "Rate": to_number(col("Rate")),
        "Discipline": col("Discipline") if mapping.get("Discipline") else (discipline or ""),
        "Work Section": col("Work Section"),
    })
    return tidy(out)


def from_boq(lines: pd.DataFrame) -> pd.DataFrame:
    """Priced BOQ lines become library entries, so this project's rates can be reused on the next one."""
    priced = lines[pd.to_numeric(lines["Rate"], errors="coerce").fillna(0) > 0]
    out = pd.DataFrame({
        "Code": [r if not AUTO_REF.match(str(r)) else "" for r in priced["Ref"]],
        "Description": priced["Description"],
        "Unit": priced["Unit"],
        "Rate": priced["Rate"],
        "Discipline": priced["Discipline"],
        "Work Section": priced["Work Section"],
    })
    return tidy(out)


def _key(text: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9.]+", " ", str(text).lower())).strip()


def merge(library: pd.DataFrame, new: pd.DataFrame) -> pd.DataFrame:
    """Add new entries; an entry with the same description and unit replaces the old one."""
    combined = tidy(pd.concat([library, new], ignore_index=True))
    keys = combined["Description"].map(_key) + "|" + combined["Unit"]
    return combined[~keys.duplicated(keep="last")].reset_index(drop=True)


def _tokens(text: str) -> set[str]:
    return {t for t in _key(text).split() if len(t) > 1 or t.isdigit()}


def _units_compatible(a: str, b: str) -> bool:
    a, b = normalise_unit(a), normalise_unit(b)
    return not a or not b or a == b


def match(lines: pd.DataFrame, library: pd.DataFrame, min_score: float = 0.8) -> pd.DataFrame:
    """Best library entry for each BOQ line: same code first, then the closest description with a compatible unit."""
    columns = ["Line", "Ref", "Description", "Unit", "Matched code", "Matched description", "Rate", "Score", "Method"]
    lib = tidy(library)
    lib = lib[lib["Rate"] > 0].reset_index(drop=True)
    if lib.empty or lines.empty:
        return pd.DataFrame(columns=columns)

    codes = {c.upper(): i for i, c in enumerate(lib["Code"]) if c}
    lib_keys = [_key(d) for d in lib["Description"]]
    lib_tokens = [_tokens(d) for d in lib["Description"]]

    rows = []
    for idx, line in lines.iterrows():
        best, score, method = None, 0.0, ""
        ref = str(line["Ref"]).strip().upper()
        if ref and not AUTO_REF.match(ref) and ref in codes and _units_compatible(line["Unit"], lib.at[codes[ref], "Unit"]):
            best, score, method = codes[ref], 1.0, "Code"
        else:
            key, tokens = _key(line["Description"]), _tokens(line["Description"])
            overlap = sorted(
                ((len(tokens & t) / max(len(tokens | t), 1), i) for i, t in enumerate(lib_tokens)
                 if tokens & t and _units_compatible(line["Unit"], lib.at[i, "Unit"])),
                reverse=True,
            )[:CANDIDATES]
            for jaccard, i in overlap:
                s = 1.0 if key == lib_keys[i] else max(jaccard, SequenceMatcher(None, key, lib_keys[i]).ratio())
                if s > score:
                    best, score = i, s
            method = "Exact" if score == 1.0 else "Similar"
        if best is not None and score >= min_score:
            rows.append({
                "Line": idx, "Ref": line["Ref"], "Description": line["Description"], "Unit": line["Unit"],
                "Matched code": lib.at[best, "Code"], "Matched description": lib.at[best, "Description"],
                "Rate": float(lib.at[best, "Rate"]), "Score": round(score * 100), "Method": method,
            })
    return pd.DataFrame(rows, columns=columns)


def apply(lines: pd.DataFrame, library: pd.DataFrame, min_score: float = 0.8, overwrite: bool = False):
    """Return (priced BOQ, match report). Lines that already have a rate keep it unless overwrite is set."""
    report = match(lines, library, min_score)
    out = lines.copy()
    if not overwrite:
        report = report[pd.to_numeric(out.loc[report["Line"], "Rate"], errors="coerce").fillna(0).values <= 0]
    out.loc[report["Line"], "Rate"] = report["Rate"].values
    return boq.finalise(out, sort=False), report.reset_index(drop=True)


def to_excel(library: pd.DataFrame, currency: str = "") -> bytes:
    """Rate library workbook: one sheet, ready to edit and upload again."""
    df = tidy(library) if not library.empty else template()
    df = df.rename(columns={"Rate": f"Rate ({currency})" if currency else "Rate"})
    buffer = io.BytesIO()
    with pd.ExcelWriter(buffer, engine="openpyxl") as writer:
        df.to_excel(writer, sheet_name="Rate Library", index=False)
        ws = writer.sheets["Rate Library"]
        for col, width in zip("ABCDEF", (12, 60, 8, 14, 16, 40)):
            ws.column_dimensions[col].width = width
        ws.freeze_panes = "A2"
    return buffer.getvalue()


def auto_map(columns) -> dict[str, str | None]:
    """Map library columns: reuses the schedule synonyms, plus a Discipline column."""
    from .schedules import auto_map as schedule_map

    found = schedule_map(columns)
    discipline = next((c for c in columns if str(c).strip().lower() in ("discipline", "disc", "trade discipline")), None)
    return {
        "Code": found["Ref"], "Description": found["Description"], "Unit": found["Unit"],
        "Rate": found["Rate"], "Discipline": discipline, "Work Section": found["Work Section"],
    }
